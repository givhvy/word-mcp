"""Generate docs/WORD_API_REFERENCE.md from this PC's Word type library (no REA needed).

Reads word-api.json (built by dump_typelib.ps1 from MSWORD.OLB; created on demand here), keeps the
interfaces and enums word-mcp works with, prints every member with its signature, and ticks the members
word_mcp_server.py actually calls - so a maintainer can see exactly which Word APIs the server depends on
and look up the alternatives next to them.

    python tools/api_reference.py            # writes docs/WORD_API_REFERENCE.md
"""

from __future__ import annotations

import json
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = os.path.join(ROOT, "word-api.json")
OUT = os.path.join(ROOT, "docs", "WORD_API_REFERENCE.md")

INTERFACES = [
    "_Application", "Documents", "_Document", "Range", "Selection", "Paragraphs", "Paragraph", "_ParagraphFormat",
    "_Font", "Find", "Replacement", "Tables", "Table", "Rows", "Row", "Columns", "Column", "Cell", "Cells",
    "Shading", "Borders", "InlineShapes", "InlineShape", "Shapes", "Comments", "Comment", "Revisions", "Revision",
    "Fields", "TablesOfContents", "TableOfContents", "Sections", "Section", "PageSetup", "HeadersFooters",
    "HeaderFooter", "PageNumbers", "Styles", "Style", "ListFormat", "ListTemplates", "ListTemplate", "ListLevels",
    "ListLevel", "Windows", "Window", "Panes", "Pane", "Pages", "Page", "View", "UndoRecord", "Options",
    "CaptionLabels", "Hyperlinks", "ContentControls", "ContentControl", "Bookmarks", "Bookmark", "Footnotes",
]
ENUMS = [
    "WdBuiltinStyle", "WdBreakType", "WdSaveFormat", "WdExportFormat", "WdParagraphAlignment", "WdColorIndex",
    "WdCaptionPosition", "WdAutoFitBehavior", "WdSortFieldType", "WdSortOrder", "WdInformation", "WdLineSpacing",
    "WdOrientation", "WdPaperSize", "WdViewType", "WdAlertLevel", "WdFindWrap", "WdReplace", "WdRevisionType",
    "WdListNumberStyle", "WdUnderline", "WdCollapseDirection", "WdTableFieldSeparator", "WdStatistic",
    "WdSpecialPane", "WdOutlineLevel", "WdContentControlType", "WdStyleType", "WdSaveOptions",
]
HIDDEN = {"QueryInterface", "AddRef", "Release", "GetTypeInfoCount", "GetTypeInfo", "GetIDsOfNames", "Invoke"}


def ensure_api():
    if not os.path.exists(API):
        subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                        os.path.join(ROOT, "dump_typelib.ps1"), "-OutJson", API], check=True)
    return json.load(open(API, encoding="utf-8"))


def used_members() -> set[str]:
    src = open(os.path.join(ROOT, "word_mcp_server.py"), encoding="utf-8").read()
    return set(re.findall(r"\.([A-Z][A-Za-z0-9]+)\b", src))


def sig(m) -> str:
    ps = ", ".join(("[" + p["name"] + "]" if p["optional"] else p["name"]) + ": " + p["type"] for p in m["params"])
    kind = {"get": "property", "put": "property (set)", "putref": "property (set ref)"}.get(m["kind"], m["kind"])
    if m["kind"] == "method":
        return f"`{m['name']}({ps})` -> {m['returns']}"
    return f"`{m['name']}` {kind}" + (f" ({ps})" if ps else "") + (f" : {m['returns']}" if m["kind"] == "get" else "")


def main():
    api = ensure_api()
    idx = {t["name"]: t for t in api}
    used = used_members()
    lines = ["# Word API reference (generated)", "",
             "Generated by `tools/api_reference.py` from this PC's Word type library (`MSWORD.OLB`, decoded by",
             "`dump_typelib.ps1`). It lists the interfaces and enums word-mcp works with; **[x]** marks members",
             "`word_mcp_server.py` calls (matched by member name, so approximate). Members the type library",
             "flags as hidden are legacy but still callable (e.g. `Comment.Author`). Regenerate it for another",
             "Word build. Search everything else with the `word_api_search` tool. Optional parameters are in",
             "[brackets]; arguments are passed positionally.", ""]
    stats = {k: 0 for k in ("dispatch", "enum", "coclass", "interface")}
    for t in api:
        stats[t["kind"]] = stats.get(t["kind"], 0) + 1
    lines += [f"Type library: {stats.get('dispatch')} dispatch interfaces, {stats.get('enum')} enums, "
              f"{stats.get('coclass')} coclasses, {stats.get('interface')} interfaces.", "", "## Interfaces", ""]
    for name in INTERFACES:
        t = idx.get(name)
        if not t:
            continue
        members, seen = [], set()
        for m in t["members"]:
            if m["name"] in HIDDEN or m["kind"] == "const":
                continue
            key = (m["name"], "prop" if m["kind"] != "method" else "method")
            if key in seen and m["kind"] in ("put", "putref"):
                # mark settable on the existing getter line instead of a second line
                for i, (k2, line) in enumerate(members):
                    if k2 == key and "(read/write)" not in line:
                        members[i] = (k2, line.replace(" property", " property (read/write)", 1))
                continue
            seen.add(key)
            members.append((key, ("- [x] " if m["name"] in used else "- [ ] ") + sig(m)
                            + (" *(hidden: legacy, still works)*" if m.get("hidden") else "")))
        n_used = sum(1 for _, l in members if l.startswith("- [x]"))
        lines += [f"### {name}  ({len(members)} members, {n_used} used)", ""] + [l for _, l in members] + [""]
    lines += ["## Enums", ""]
    for name in ENUMS:
        t = idx.get(name)
        if not t:
            continue
        lines.append(f"### {name}")
        lines.append("")
        lines.append(", ".join(f"`{m['name']}={m['value']}`" for m in t["members"]))
        lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT}: {len(lines)} lines")


if __name__ == "__main__":
    main()
